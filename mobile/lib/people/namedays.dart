const _ka = 'აბგდევზთიკლმნოპჟრსტუფქღყშჩცძწჭხჯჰ';
const _la = ['a', 'b', 'g', 'd', 'e', 'v', 'z', 't', 'i', 'k', 'l', 'm', 'n', 'o', 'p', 'zh', 'r', 's', 't', 'u', 'p', 'k', 'gh', 'q', 'sh', 'ch', 'ts', 'dz', 'ts', 'ch', 'kh', 'j', 'h'];

/// Georgian letters in Latin ones, as the site spells names typed in Latin
String latn(String s) => s.split('').map((c) {
      final i = _ka.indexOf(c);
      return i < 0 ? c : _la[i];
    }).join();

final Map<String, List<(String, String)>> _index = () {
  final m = <String, List<(String, String)>>{};
  for (final (names, dates) in nameDays) {
    for (final n in names) {
      final vs = [n, if (!RegExp('[აეიოუ]\$').hasMatch(n)) '${n}ი'];
      for (final v in vs) {
        m[v] = dates;
        m[latn(v)] = dates;
      }
    }
  }
  return m;
}();

String firstName(String name) {
  final t = name.trim().split(RegExp(r'\s+'));
  return t.isEmpty ? '' : t.first.toLowerCase();
}

/// the calendar's days for a first name
List<(String, String)> daysOfName(String name) => _index[firstName(name)] ?? const [];

/// a person's days: their own choice first, otherwise the calendar by their first name
List<(String, String)> nameDaysOf(String name, String? own, String? ownLabel) =>
    own != null && own.isNotEmpty ? [(own, (ownLabel ?? '').isEmpty ? 'ანგელოზის დღე' : ownLabel!)] : daysOfName(name);

/// "27 იანვარი"
String mdText(String md) {
  final p = md.split('-');
  final m = int.tryParse(p.first) ?? 1, d = int.tryParse(p.length > 1 ? p[1] : '') ?? 1;
  return '$d ${monthNames[(m - 1).clamp(0, 11)]}';
}

String mdOf(DateTime d) => '${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';

/// in how many days it comes next (0: today)
int daysUntil(String md, [DateTime? now]) {
  final n = now ?? DateTime.now(), today = DateTime(n.year, n.month, n.day);
  final p = md.split('-');
  final m = int.tryParse(p.first) ?? 1, d = int.tryParse(p.length > 1 ? p[1] : '') ?? 1;
  var dt = DateTime(today.year, m, d);
  if (dt.isBefore(today)) dt = DateTime(today.year + 1, m, d);
  return dt.difference(today).inDays;
}

String whenText(int n) => n == 0 ? 'დღეს' : (n == 1 ? 'ხვალ' : '$n დღეში');

/// what is celebrated on a day, and by which names
List<(String, List<String>)> feastsOn(String md) {
  final m = <String, List<String>>{};
  for (final (names, dates) in nameDays) {
    for (final (d, label) in dates) {
      if (d == md) (m[label] ??= []).addAll(names);
    }
  }
  return [for (final e in m.entries) (e.key, e.value)];
}
